`timescale 1ns / 1ps

// ============================================================================
// 双控开关（组合逻辑示例，对应 E4 讲义“示例: 双控开关”）
//
// 两个开关 a、b 联合控制同一盏灯 f：
//   f = a ^ b
// 任意拨动一个开关，灯的状态就会翻转，这就是常见的“双控开关”。
//
// 这个模块没有时钟，是纯组合逻辑，C++ 驱动中调用 eval() 后立即得到结果。
// ============================================================================
module top (
  input  wire a,
  input  wire b,
  output wire f
);

  assign f = a ^ b;  // 异或：a、b 不同时 f 为 1

endmodule
