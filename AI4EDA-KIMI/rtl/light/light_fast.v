`timescale 1ns / 1ps

// ============================================================================
// 流水灯的“仿真加速”包装
//
// light 默认 5000000 个周期才移位一次，在纯仿真中要跑很久才能看到 16 位
// 全部轮转一遍。这里把 CNT_MAX 改小为 4（每 5 个周期移位一次），
// 让 C++ 驱动可以在几百个周期内完成完整的自动检查。
//
// 注意：NVBoard 演示仍使用 light 本身（CNT_MAX = 5000000），这样灯的
// 移动速度接近真实板卡上的视觉效果。
// ============================================================================
module light_fast (
  input  wire        clk,
  input  wire        rst,
  output wire [15:0] led
);

  light #(
    .CNT_MAX(4)
  ) u_light (
    .clk(clk),
    .rst(rst),
    .led(led)
  );

endmodule
